// One-time setup script: uploads the placement tile icons in
// assets/placement-icons/ as application emojis (owned by the bot, usable
// in every server it's in, no cost, no per-guild emoji-slot usage).
// Re-running is safe — tiles that already exist as application emojis are
// left alone and just reused.
//
// Usage: node scripts/upload-placement-emojis.js
// Writes the resulting <:name:id> mentions to src/placementEmojis.js.

const fs = require('fs');
const path = require('path');
const { Client, GatewayIntentBits } = require('discord.js');
const { DISCORD_TOKEN } = require('../src/config');

const ICONS_DIR = path.join(__dirname, '..', 'assets', 'placement-icons');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'placementEmojis.js');

const PLACEMENTS = [1, 2, 3, 4, 5, 6, 7, 8];
const VARIANTS = ['good', 'bad'];

const client = new Client({ intents: [GatewayIntentBits.Guilds] });

client.once('clientReady', async () => {
  try {
    const existing = await client.application.emojis.fetch();
    const mentions = {};

    for (const placement of PLACEMENTS) {
      mentions[placement] = {};
      for (const variant of VARIANTS) {
        const name = `placement_${placement}_${variant}`;
        const already = existing.find((emoji) => emoji.name === name);
        if (already) {
          console.log(`Skipping ${name} — already exists`);
          mentions[placement][variant] = already.toString();
          continue;
        }

        const emoji = await client.application.emojis.create({
          attachment: path.join(ICONS_DIR, `${placement}-${variant}.png`),
          name,
        });
        console.log(`Uploaded ${name}`);
        mentions[placement][variant] = emoji.toString();
      }
    }

    const lines = PLACEMENTS.map(
      (placement) =>
        `  ${placement}: { good: '${mentions[placement].good}', bad: '${mentions[placement].bad}' },`,
    );
    const content = `// Generated by scripts/upload-placement-emojis.js — do not edit by hand.\nmodule.exports = {\n${lines.join('\n')}\n};\n`;
    fs.writeFileSync(OUTPUT_FILE, content);
    console.log(`Wrote ${OUTPUT_FILE}`);
  } catch (err) {
    console.error('Failed to upload placement emojis:', err);
  } finally {
    client.destroy();
  }
});

client.login(DISCORD_TOKEN);
