// One-time setup script: uploads the rank tier icons in assets/rank-icons/ as
// application emojis (owned by the bot, usable in every server it's in, no
// cost, no per-guild emoji-slot usage). Re-running is safe — tiers that
// already exist as application emojis are left alone and just reused.
//
// Usage: node scripts/upload-rank-emojis.js
// Writes the resulting <:name:id> mentions to src/rankEmojis.js.

const fs = require('fs');
const path = require('path');
const { Client, GatewayIntentBits } = require('discord.js');
const { DISCORD_TOKEN } = require('../src/config');

const ICONS_DIR = path.join(__dirname, '..', 'assets', 'rank-icons');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'rankEmojis.js');

const TIERS = [
  'iron',
  'bronze',
  'silver',
  'gold',
  'platinum',
  'emerald',
  'diamond',
  'master',
  'grandmaster',
  'challenger',
];

const client = new Client({ intents: [GatewayIntentBits.Guilds] });

client.once('clientReady', async () => {
  try {
    const existing = await client.application.emojis.fetch();
    const mentions = {};

    for (const tier of TIERS) {
      const name = `rank_${tier}`;
      const already = existing.find((emoji) => emoji.name === name);
      if (already) {
        console.log(`Skipping ${name} — already exists`);
        mentions[tier] = already.toString();
        continue;
      }

      const emoji = await client.application.emojis.create({
        attachment: path.join(ICONS_DIR, `${tier}.png`),
        name,
      });
      console.log(`Uploaded ${name}`);
      mentions[tier] = emoji.toString();
    }

    const lines = Object.entries(mentions).map(([tier, mention]) => `  ${tier}: '${mention}',`);
    const content = `// Generated by scripts/upload-rank-emojis.js — do not edit by hand.\nmodule.exports = {\n${lines.join('\n')}\n};\n`;
    fs.writeFileSync(OUTPUT_FILE, content);
    console.log(`Wrote ${OUTPUT_FILE}`);
  } catch (err) {
    console.error('Failed to upload rank emojis:', err);
  } finally {
    client.destroy();
  }
});

client.login(DISCORD_TOKEN);
